export function t(lang, key, vars = {}) {
  const table = DICT[lang] || DICT.km;
  const template = table[key] || DICT.km[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}

export function sideLabel(lang, side) {
  return t(lang, side === "bride" ? "bride" : "groom");
}

export function methodLabel(lang, method) {
  return t(lang, method === "khqr" ? "khqr" : "cash");
}
